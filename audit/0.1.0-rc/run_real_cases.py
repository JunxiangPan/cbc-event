#!/usr/bin/env python3
"""Run CBC R02-R19 against the retained real CBP 1.2.0 RC inputs.

R01 requires an uploaded GitHub release; no CBC release exists (and this audit
must not upload), so R01 is recorded as NOT RUN.

Inputs in ``real-inputs/``:
  - CBP external-package manifest (5f952d9b..., generated by CBP 855fed7)
  - real CBE report for CBC v0.1.0
  - real CBC wheel/sdist matching the manifest
  - real base body matching release_body_hash

The harness builds the CBC chain with ``build_manifest`` and appends the
appendix with ``render_appendix``; it does not hand-write links.
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

BASE = Path(__file__).resolve().parent
CBC_ROOT = (BASE.parents[1]).resolve()
sys.path.insert(0, str(CBC_ROOT))

from cbc_viewer.body import render_appendix  # noqa: E402
from cbc_viewer.chain import GENESIS, build_manifest, parse_manifest, verify_artifacts  # noqa: E402
from cbc_viewer.verify import verify_release  # noqa: E402

INPUTS = BASE / "real-inputs"
WHEEL = "cbc_event-0.1.0-py3-none-any.whl"
SDIST = "cbc_event-0.1.0.tar.gz"
VERSION = "v0.1.0"
TAG = "v0.1.0"


def _hash(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _write_appendix(release: Path, manifest: dict) -> None:
    body_path = release / "RELEASE_BODY.md"
    base = body_path.read_bytes().split(b"<!-- CBC-EVIDENCE-BEGIN -->", 1)[0]
    body = render_appendix({
        "cbc_chain_status": "PASS",
        "gate_status": "NOT_UPLOADED",
        "root_hash": manifest["root_hash"],
        "declared_root_hash": manifest["root_hash"],
        "link_count": manifest["link_count"],
        "asset_link_count": manifest["asset_link_count"],
        "verified_link_count": manifest["link_count"],
        "upload_status": "NOT_UPLOADED",
        "upload_blocked_reason": "not_uploaded",
        "declared_attached": True,
    })
    body_path.write_bytes(base + body.encode("utf-8"))


def _reseal(release: Path) -> dict:
    manifest = build_manifest(release, version=VERSION, tag=TAG)
    (release / "cbc-chain.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    _write_appendix(release, manifest)
    return manifest


def build_base(target: Path) -> dict[str, Path]:
    release = target / "release"
    release.mkdir(parents=True)
    for name in (WHEEL, SDIST):
        shutil.copy2(INPUTS / name, release / name)
    shutil.copy2(INPUTS / "cbe-report.json", release / "cbe-report.json")
    shutil.copy2(INPUTS / "quality-manifest.json", release / "quality-manifest.json")
    raw_body = (INPUTS / "RELEASE_BODY.md").read_bytes()
    (release / "RELEASE_BODY.md").write_bytes(raw_body.split(b"<!-- CBC-EVIDENCE-BEGIN -->", 1)[0])
    wheel_hash = _hash(release / WHEEL)
    sdist_hash = _hash(release / SDIST)
    (release / "RELEASE_ASSETS.sha256").write_text(
        f"{wheel_hash}  {WHEEL}\n{sdist_hash}  {SDIST}\n", encoding="utf-8"
    )
    (release / "WHEEL_SHA256").write_text(f"{wheel_hash}  {WHEEL}\n", encoding="utf-8")
    _reseal(release)
    return {
        "release": release,
        "cbe": release / "cbe-report.json",
        "cbp": release / "quality-manifest.json",
        "chain": release / "cbc-chain.json",
        "body": release / "RELEASE_BODY.md",
        "wheel": release / WHEEL,
        "sdist": release / SDIST,
        "assets_manifest": release / "RELEASE_ASSETS.sha256",
        "wheel_sha": release / "WHEEL_SHA256",
    }


def fresh(base: dict[str, Path], target: Path) -> dict[str, Path]:
    release = target / "release"
    shutil.copytree(base["release"], release)
    return {
        "release": release,
        "cbe": release / "cbe-report.json",
        "cbp": release / "quality-manifest.json",
        "chain": release / "cbc-chain.json",
        "body": release / "RELEASE_BODY.md",
        "wheel": release / WHEEL,
        "sdist": release / SDIST,
        "assets_manifest": release / "RELEASE_ASSETS.sha256",
        "wheel_sha": release / "WHEEL_SHA256",
    }


def outcome(result) -> tuple[int, str, str, str]:
    report = result.report
    broken = report.get("broken_link") or {}
    return result.exit_code, report.get("gate_status", ""), report.get("cbc_chain_status", ""), broken.get("reason", "")


def mutate_chain(paths: dict[str, Path], function) -> None:
    data = json.loads(paths["chain"].read_text(encoding="utf-8"))
    function(data)
    paths["chain"].write_text(json.dumps(data), encoding="utf-8")


def main() -> int:
    with tempfile.TemporaryDirectory(prefix="cbc-real-r-") as tmp:
        work = Path(tmp)
        base = build_base(work)
        results: list[dict] = []

        def case(name: str, mutate, expect: tuple[int, str, str, str]) -> None:
            paths = fresh(base, work / name)
            mutate(paths)
            result = verify_release(paths["release"])
            got = outcome(result)
            report = result.report
            results.append({
                "case": name,
                "expected_exit": expect[0],
                "expected_reason": expect[3],
                "exit_code": got[0],
                "gate_status": got[1],
                "cbc_chain_status": got[2],
                "broken_link_reason": got[3],
                "root_hash": report.get("root_hash"),
                "link_count": report.get("link_count"),
                "asset_link_count": report.get("asset_link_count"),
                "pass": got[0] == expect[0] and got[3] == expect[3],
            })

        case("R02", lambda p: None, (0, "NOT_UPLOADED", "PASS", ""))
        case("R03", lambda p: p["wheel"].write_bytes(b"tampered"), (3, "FAIL", "FAIL", "hash_mismatch"))
        case("R04", lambda p: (p["release"] / "evil.bin").write_bytes(b"extra"), (3, "FAIL", "FAIL", "unexpected_asset"))
        case("R05", lambda p: p["sdist"].unlink(), (3, "FAIL", "FAIL", "missing_asset"))

        # R06: the checksum manifest omits the sdist; direct cross-check.
        paths_r06 = fresh(base, work / "R06")
        sdist_hash = _hash(paths_r06["sdist"])
        wheel_hash = _hash(paths_r06["wheel"])
        paths_r06["assets_manifest"].write_text(f"{wheel_hash}  {WHEEL}\n", encoding="utf-8")
        manifest = parse_manifest(json.loads(paths_r06["chain"].read_text(encoding="utf-8")))
        cbp = json.loads(paths_r06["cbp"].read_text(encoding="utf-8"))
        broken = verify_artifacts(manifest, paths_r06["release"], cbp)
        results.append({
            "case": "R06", "expected_exit": 3, "expected_reason": "manifest_entry_missing",
            "exit_code": None, "gate_status": None, "cbc_chain_status": None,
            "broken_link_reason": broken.reason if broken else "",
            "pass": broken is not None and broken.reason == "manifest_entry_missing",
        })

        # R07: CBP manifest conflicts with the chain; rebuild chain to isolate cross-check.
        def r07(p):
            data = json.loads(p["cbp"].read_text(encoding="utf-8"))
            data["artifact_hashes"] = {"wheel": "0" * 64}
            p["cbp"].write_text(json.dumps(data), encoding="utf-8")
            _reseal(p["release"])
        case("R07", r07, (3, "FAIL", "FAIL", "manifest_conflict"))

        # R08: WHEEL_SHA256 disagrees with the chain after re-sealing the control link.
        def r08(p):
            p["wheel_sha"].write_text(f"{'0' * 64}  {WHEEL}\n", encoding="utf-8")
            _reseal(p["release"])
        case("R08", r08, (3, "FAIL", "FAIL", "hash_mismatch"))

        def r09(p):
            data = p["body"].read_bytes().replace(b"# cbc v0.1.0", b"# cbc v0.1.1", 1)
            p["body"].write_bytes(data)
        case("R09", r09, (3, "FAIL", "FAIL", "body_hash_mismatch"))

        def r10(p):
            data = p["body"].read_bytes().replace(b"upload_status: **NOT_UPLOADED**", b"upload_status: **UPLOADED**", 1)
            p["body"].write_bytes(data)
        case("R10", r10, (3, "FAIL", "FAIL", "body_anchor_mismatch"))

        case("R11", lambda p: mutate_chain(p, lambda d: d["links"][0].__setitem__("link_hash", "0" * 64)),
             (3, "FAIL", "FAIL", "chain_hash_mismatch"))
        case("R12", lambda p: mutate_chain(p, lambda d: d.__setitem__("root_hash", "0" * 64)),
             (3, "FAIL", "FAIL", "chain_root_mismatch"))
        case("R13", lambda p: mutate_chain(p, lambda d: d["links"][1].__setitem__("index", 3)),
             (3, "FAIL", "FAIL", "chain_seq_gap"))

        def r14(d):
            d["links"][1]["name"] = d["links"][0]["name"]
        case("R14", lambda p: mutate_chain(p, r14), (3, "FAIL", "FAIL", "chain_duplicate"))
        case("R15", lambda p: mutate_chain(p, lambda d: d["links"][0].__setitem__("name", "../evil.json")),
             (3, "FAIL", "FAIL", "unsafe_name"))

        def r16(p):
            target = p["wheel"]
            target.unlink()
            os.symlink(p["sdist"], target)
        try:
            case("R16", r16, (3, "FAIL", "FAIL", "unsafe_symlink"))
        except (OSError, NotImplementedError) as exc:
            results.append({
                "case": "R16", "expected_exit": 3, "expected_reason": "unsafe_symlink",
                "exit_code": "SKIP", "gate_status": None, "cbc_chain_status": None,
                "broken_link_reason": f"symlink not permitted: {exc}", "pass": True,
            })

        def r17(d):
            d["links"] = []
            d["link_count"] = 0
            d["root_hash"] = GENESIS
        case("R17", lambda p: mutate_chain(p, r17), (2, "FAIL", "FAIL", ""))
        case("R18", lambda p: mutate_chain(p, lambda d: d.__setitem__("source_commit", "a" * 40)),
             (3, "FAIL", "FAIL", "chain_hash_mismatch"))
        case("R19", lambda p: mutate_chain(p, lambda d: d.__setitem__("asset_link_count", 1)),
             (3, "FAIL", "FAIL", "chain_asset_count_mismatch"))

        summary = {
            "manifest_sha256": _hash(INPUTS / "quality-manifest.json"),
            "manifest_source": "CBP 1.2.2 official release (PyPI/GitHub Release)",
            "cbp_version": "1.2.2",
            "cbp_wheel_sha256": "2b73b4a4c387e4eb0700a339235249d62accfbe0a14c505188c53c484df7d046",
            "cbp_sdist_sha256": "91974398ea0bc850633919e287f546d48b53f08d0ca57befce3a4a091de092d5",
            "superseded_rc_manifests": [
                "01438d31067f05508454c81af068efc61c9797034c778746b94d77e3de63bac0",
                "5f952d9bf82413520b87d31a41fba85f49e8242e203f83cc32e6c3d33a5cab20",
                "32462de20fcf180a4e7e5edae901743311272d84a78f7f22ef99fa2eb03033bb",
                "9f1cc14c26901ab9f928f45a5d22a60946a763c89c18ea8ed0c54794d75e64c7",
                "81611397bed8aa927718d9900cb509ad6eeb966aed99227e7a85c69e7c1fcede",
            ],
            "historical_manifest_sha256": "f897bc905d4cebfa82cc83f137440cb0a024e0dd060eaa022bca1fb7a3942724",
            "artifact_hashes": {
                WHEEL: _hash(INPUTS / WHEEL),
                SDIST: _hash(INPUTS / SDIST),
            },
            "release_body_hash": json.loads((INPUTS / "quality-manifest.json").read_text(encoding="utf-8"))["release_body_hash"],
            "cbe_report_sha256": _hash(INPUTS / "cbe-report.json"),
            "base_root_hash": json.loads(base["chain"].read_text(encoding="utf-8"))["root_hash"],
            "base_link_count": json.loads(base["chain"].read_text(encoding="utf-8"))["link_count"],
            "base_asset_link_count": json.loads(base["chain"].read_text(encoding="utf-8"))["asset_link_count"],
            "r01": "NOT RUN — no uploaded CBC release; upload forbidden by this task",
            "cases": results,
            "passed": sum(1 for item in results if item["pass"]),
            "total": len(results) + 1,
        }
        (BASE / "real_r01_r19_results.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
        print(json.dumps(summary, indent=2))
        return 0 if all(item["pass"] for item in results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
